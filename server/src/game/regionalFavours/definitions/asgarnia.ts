function skillAct(
    id: string,
    giver: number,
    actionIds: readonly string[],
    area: TileBounds,
    label: string,
    skillId: SkillId,
    minLevel: number,
    difficulty: RegionalFavourDefinition["reward"]["difficulty"],
    opts?: {
        amount?: [number, number];
        objectNames?: readonly string[];
        turnIn?: number;
        travelDistance?: number;
    },
): RegionalFavourDefinition {
    const [minAmount, maxAmount] = opts?.amount ?? [1, 1];
    const turnIn = opts?.turnIn ?? giver;
    return {
        id,
        region: "asgarnia",
        giverNpcId: giver,
        turnInNpcId: turnIn,
        category: "PERFORM_SKILL_ACTION",
        reward: {
            kind: "skill_xp",
            skillId,
            difficulty,
            travelDistance: opts?.travelDistance,
        },
        skillActionIds: [...actionIds],
        targetArea: area,
        targetObjectNames: opts?.objectNames ? [...opts.objectNames] : undefined,
        minAmount,
        maxAmount,
        requirements: minLevel > 1 ? [{ skillId, level: minLevel }] : undefined,
        baseWeight: 11,
        acceptsExistingItems: false,
        requiresPostAssignmentProgress: true,
        objectiveText: label,
        instructionText: `${label} after accepting this favour, then return.`,
        assignmentDialog: [label, "Come back when it's done."],
        completionDialog: ["Nice work.", "Here's your reward."],
        recommendedSkillId: skillId,
        recommendedLevelMin: minLevel,
        recommendedLevelMax: minLevel + 20,
    };
}

