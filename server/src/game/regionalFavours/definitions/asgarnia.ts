/**
 * Combat favour tiered by the monster's OSRS combat level.
 * recommended band stays tight around monsterCb so high-level players
 * are steered toward harder targets (Guards → Hill Giants → Ice Warriors…).
 */
function kill(
    id: string,
    giver: number,
    npcIds: readonly number[],
    label: string,
    minAmount: number,
    maxAmount: number,
    monsterCb: number,
    difficulty: RegionalFavourDefinition["reward"]["difficulty"],
): RegionalFavourDefinition {
    const minCombat = Math.max(1, monsterCb - 8);
    return {
        id,
        region: "asgarnia",
        giverNpcId: giver,
        turnInNpcId: giver,
        category: "KILL_NPC",
        reward: { kind: "combat_lamp", difficulty },
        targetNpcIds: [...npcIds],
        minAmount,
        maxAmount,
        minCombatLevel: minCombat,
        baseWeight: 12,
        acceptsExistingItems: false,
        requiresPostAssignmentProgress: true,
        objectiveText: `Kill ${label}.`,
        instructionText: `Defeat ${label} in Asgarnia after accepting this favour, then return.`,
        assignmentDialog: [`We've had trouble with ${label}.`, "Deal with them, then report back."],
        completionDialog: [
            "The area should be safer now.",
            "Take these coins and a combat lamp for your efforts.",
        ],
        recommendedLevelMin: Math.max(1, monsterCb - 2),
        recommendedLevelMax: monsterCb + 12,
    };
}

